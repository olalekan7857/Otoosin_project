def _env_bool(name, default):
    raw_value = config(name, default=str(default))
    value = str(raw_value).strip().lower()
    if value in {"1", "true", "yes", "on"}:
        return True
    if value in {"0", "false", "no", "off"}:
        return False
    raise ImproperlyConfigured(
        f"{name} must be a boolean value (true/false, yes/no, 1/0)."
    )


def _env_list(name, default=""):
    raw_value = config(name, default=default)
    return [
        item.strip()
        for item in str(raw_value).split(",")
        if item.strip()
    ]


def _env_int(name, default, *, minimum=None):
    try:
        value = int(str(config(name, default=str(default))).strip())
    except (TypeError, ValueError) as error:
        raise ImproperlyConfigured(
            f"{name} must be an integer value."
        ) from error
    if minimum is not None and value < minimum:
        raise ImproperlyConfigured(
            f"{name} must be greater than or equal to {minimum}."
        )
    return value


def _env_path(name, default):
    raw = str(config(name, default=str(default))).strip()
    path = Path(raw or default)
    if not path.is_absolute():
        path = BASE_DIR / path
    return path


def _validated_hosts(hosts):
    for host in hosts:
        if host == "*":
            continue
        if "://" in host or "/" in host or " " in host:
            raise ImproperlyConfigured(
                "ALLOWED_HOSTS entries must be hostnames, not URLs."
            )
        try:
            parsed = urlsplit(f"//{host}")
            port = parsed.port
        except ValueError as error:
            raise ImproperlyConfigured(
                "ALLOWED_HOSTS entries must be valid hostnames."
            ) from error
        if not parsed.hostname or port is not None:
            raise ImproperlyConfigured(
                "ALLOWED_HOSTS entries must be hostnames without ports."
            )
    return hosts


def _validated_origins(origins):
    validated = []
    for origin in origins:
        normalized = origin.rstrip("/")
        parsed = urlsplit(normalized)
        if (
            parsed.scheme not in {"http", "https"}
            or not parsed.netloc
            or parsed.path
            or parsed.query
            or parsed.fragment
            or parsed.username
            or parsed.password
        ):
            raise ImproperlyConfigured(
                "CSRF_TRUSTED_ORIGINS entries must be http(s) origins "
                "without paths, queries or credentials."
            )
        validated.append(normalized)
    return validated


